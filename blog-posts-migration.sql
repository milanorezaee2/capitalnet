CREATE TABLE IF NOT EXISTS public.blog_posts (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  title         TEXT NOT NULL,
  slug          TEXT UNIQUE,
  category      TEXT,
  tags          TEXT[],
  excerpt       TEXT NOT NULL DEFAULT '',
  content       TEXT NOT NULL DEFAULT '',
  cover_image   TEXT,
  author_name   TEXT NOT NULL DEFAULT 'تیم CapNet',
  author_role   TEXT NOT NULL DEFAULT '',
  published_at  TIMESTAMPTZ,
  read_time     TEXT NOT NULL DEFAULT '۵ دقیقه',
  featured      BOOLEAN NOT NULL DEFAULT FALSE,
  status        TEXT NOT NULL DEFAULT 'draft'
                CHECK (status IN ('draft', 'published', 'scheduled')),
  views         INTEGER NOT NULL DEFAULT 0,
  likes         INTEGER NOT NULL DEFAULT 0
);

-- ──────────────────────────────────────────────────────────────
-- 2. Row Level Security
-- ──────────────────────────────────────────────────────────────
ALTER TABLE public.blog_posts ENABLE ROW LEVEL SECURITY;

-- Public can read published posts
DROP POLICY IF EXISTS "Public read published posts" ON public.blog_posts;
CREATE POLICY "Public read published posts"
  ON public.blog_posts FOR SELECT
  USING (status = 'published');

-- Admin has full access (INSERT/UPDATE/DELETE/SELECT) — anon/regular users cannot write
DROP POLICY IF EXISTS "Service role full access blog" ON public.blog_posts;
DROP POLICY IF EXISTS "Admin full access blog" ON public.blog_posts;
CREATE POLICY "Admin full access blog"
  ON public.blog_posts FOR ALL
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.admins
      WHERE email = auth.email() AND is_active = true
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.admins
      WHERE email = auth.email() AND is_active = true
    )
  );

